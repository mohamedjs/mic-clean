#!/usr/bin/env node
// Checks that need no sound server: run with `npm test`.
// Golden files in test/golden were captured from the code before the restructure.
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

process.env.MIC_STATE_DIR = fs.mkdtempSync(path.join(require('os').tmpdir(), 'mic-clean-test-'));
// The chain test must not depend on swh-plugins being installed here (CI has none).
process.env.SC4M_LADSPA = path.join(process.env.MIC_STATE_DIR, 'sc4m_1916.so');
fs.writeFileSync(process.env.SC4M_LADSPA, '');
const G = (f) => path.join(__dirname, 'golden', f);
const ROOT = path.join(__dirname, '..');
const { parsePactlList, classifySource } = require('../src/modules/linux/pactl');
const { buildChainConf } = require('../src/modules/linux/chain-conf');
const settings = require('../src/modules/settings');
const P = require('../src/shared/presets');

const stamp = (s) => s.replace(/— .*Z/, '— TS').replace(/Generated by .* — TS/, 'Generated by X — TS').replace(/plugin = "[^"]*sc4m_1916\.so"/g, 'plugin = "SC4M"');
// Old names → new names: the only intended difference in the generated chain.
const rename = (s) => s.replace(/Mic \(Mohamed\) Dashboard/g, 'X').replace(/mic_mohamed/g, 'mic_clean').replace(/Mic \(Mohamed\)/g, 'Mic Clean');

test('chain config is unchanged for every preset (apart from the new name)', () => {
  const gold = JSON.parse(fs.readFileSync(G('chains.json'), 'utf8'));
  const D = settings.DEFAULT_SETTINGS;
  const want = (k) => stamp(rename(gold[k]));
  for (const [k, v] of Object.entries(P.SCENES)) {
    const st = { ...structuredClone(D), ...v.s, eq: D.eq.map((b, i) => ({ ...b, gain: v.s.eq[i] })) };
    assert.strictEqual(stamp(buildChainConf(st, '/usr/lib/ladspa/librnnoise_ladspa.so')), want(k), k);
  }
  assert.strictEqual(stamp(buildChainConf(D, '/usr/lib/ladspa/librnnoise_ladspa.so')), want('default'));
  assert.strictEqual(stamp(buildChainConf({ ...D, master: 'alsa_input.x' }, '/x.so')), want('withMaster'));
  assert.strictEqual(stamp(buildChainConf(D, null)), want('noRn'));
});

test('presets match the dashboard scenes captured before the move', () => {
  const gold = JSON.parse(fs.readFileSync(G('scenes.json'), 'utf8'));
  assert.deepStrictEqual(JSON.parse(JSON.stringify(P.SCENES)), gold);
  assert.deepStrictEqual(P.EQ_PRESETS.podcast, P.SCENES.podcast.s.eq);
});

test('default settings are the podcast scene and follow the system default mic', () => {
  const D = settings.DEFAULT_SETTINGS;
  for (const [k, v] of Object.entries(P.SCENES.podcast.s)) {
    if (k === 'eq') assert.deepStrictEqual(D.eq.map((b) => b.gain), v);
    else assert.strictEqual(D[k], v, k);
  }
  assert.strictEqual(D.master, '');
  assert.strictEqual(D.profile, 'podcast');
});

test('pactl parsing and source classification are unchanged', () => {
  const gold = JSON.parse(fs.readFileSync(G('parsed.json'), 'utf8'));
  const mods = parsePactlList(fs.readFileSync(G('pactl-modules.txt'), 'utf8'), 'Module');
  const by = Object.fromEntries(mods.map((m) => [m.index, m]));
  const src = parsePactlList(fs.readFileSync(G('pactl-sources.txt'), 'utf8'), 'Source');
  assert.deepStrictEqual(src, gold.src);
  const norm = (c) => JSON.parse(rename(JSON.stringify(c)).replace(/Mic Clean \(من الداشبورد دي\)/, 'X').replace(/مايك وهمي عاملته الداشبورد دي — بيتشال لما تقفل السيرفر./, 'Y'));
  const got = src.map((x) => classifySource(x, by)).map((c) => JSON.parse(JSON.stringify(c).replace(/Mic Clean \(من الأبلكيشن ده\)/, 'X').replace(/المايك النضيف اللي عامله الأبلكيشن ده — بيتشال لما تقفله./, 'Y')));
  assert.deepStrictEqual(got, gold.cls.map(norm));
});

test('every OS mode serves every old route plus the new ones', () => {
  const old = JSON.parse(fs.readFileSync(G('routes-linux.json'), 'utf8'));
  for (const [mode, env] of [['linux', { MIC_PLATFORM: 'linux' }], ['darwin', { MIC_PLATFORM: 'darwin' }], ['win32', { MIC_PLATFORM: 'win32' }], ['web', { MIC_PLATFORM: 'linux', MIC_ENGINE: 'web' }]]) {
    const r = spawnSync(process.execPath, ['-e', "console.log(JSON.stringify(Object.keys(require('./src/server').buildRoutes())))"], { cwd: ROOT, env: { ...process.env, ...env }, encoding: 'utf8' });
    assert.strictEqual(r.status, 0, r.stderr);
    const keys = JSON.parse(r.stdout);
    for (const k of old) assert.ok(keys.includes(k), `${mode}: ${k}`);
    for (const k of ['GET /api/deps', 'GET /api/app']) assert.ok(keys.includes(k), `${mode}: ${k}`);
  }
});

test('no file still says Mic (Mohamed) where people see it', () => {
  const files = spawnSync('git', ['ls-files', '-co', '--exclude-standard'], { cwd: ROOT, encoding: 'utf8' }).stdout.split('\n')
    .filter((f) => f && /\.(js|html|json|webmanifest|sh|ps1|md|yml|rb)$/.test(f) && !f.startsWith('test/') && !f.includes('node_modules') && f !== 'src/modules/migrate/index.js' && fs.existsSync(path.join(ROOT, f)));
  // lines that talk about the old name on purpose (migration) are fine
  const bad = files.filter((f) => fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').some((l) => /Mic \(Mohamed\)/.test(l) && !/used to be called|Coming from|كان اسمه|\.lnk/.test(l)));
  assert.deepStrictEqual(bad, []);
});
